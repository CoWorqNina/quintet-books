import { Hono } from "hono";
import { toDbEntry } from "../../shared/entries";
import type { AccountTotal } from "../../shared/ledger";
import type { Book } from "../../shared/types";
import { closingEntry } from "../../shared/yearEnd";
import { isOwner, seesEverything, todayManila } from "../access";
import { getAccounts } from "../airtable";
import { badRequest, dbError, forbidden } from "../db";
import type { AppContext } from "../env";
import { existingGenerated } from "../monthEnd";
import { serviceClient } from "../supabase";

// Year-end close: one Closing entry per book on December 31, generated by an Owner and
// approved by the other Owner.
export const yearEnd = new Hono<AppContext>();
type DB = ReturnType<typeof serviceClient>;
const BOOKS: Book[] = ["Store", "Commissary"];

function yearParam(v: string): number {
  const y = Number(v);
  if (!Number.isInteger(y) || y < 2026 || y > 2100) badRequest("Choose a year.");
  return y;
}

/** What is still open per book (approved entries), and the closing entries already made. */
export async function yearEndStatus(db: DB, env: AppContext["Bindings"], year: number) {
  const [{ data, error }, accounts, existing, pending] = await Promise.all([
    db.rpc("account_totals", { p_to: `${year}-12-31`, p_year_start: `${year}-01-01`, p_mode: "post-closing" }),
    getAccounts(env),
    existingGenerated(db, `${year}-12`),
    db.from("entries").select("id", { count: "exact", head: true }).in("status", ["Draft", "Submitted"]).gte("entry_date", `${year}-01-01`).lte("entry_date", `${year}-12-31`),
  ]);
  dbError(error);
  dbError(pending.error);
  const map = new Map(accounts.map((a) => [a.code, a]));
  return {
    pendingEntries: pending.count ?? 0,
    books: BOOKS.map((book) => ({
      book,
      existing: existing.filter((e) => e.generated === "closing" && e.book === book),
      proposal: closingEntry(year, book, (data ?? []) as AccountTotal[], map),
    })),
  };
}

yearEnd.get("/:year", async (c) => {
  if (!seesEverything(c.get("user"))) forbidden();
  const year = yearParam(c.req.param("year"));
  return c.json({ year, canClose: todayManila() >= `${year}-12-31`, ...(await yearEndStatus(serviceClient(c.env), c.env, year)) });
});

yearEnd.post("/:year", async (c) => {
  const user = c.get("user");
  if (!isOwner(user)) forbidden("Only an Owner closes the year.");
  const year = yearParam(c.req.param("year"));
  const { book } = await c.req.json<{ book: Book }>();
  if (todayManila() < `${year}-12-31`) badRequest(`The year can be closed from December 31, ${year}.`);
  const db = serviceClient(c.env);
  const status = await yearEndStatus(db, c.env, year);
  if (status.pendingEntries) badRequest(`${status.pendingEntries} entries in ${year} are still waiting for approval. Approve or cancel them first.`);
  const b = status.books.find((x) => x.book === book);
  if (!b) badRequest("Choose a book.");
  const waiting = b.existing.find((e) => e.status !== "Approved");
  if (waiting) badRequest(`Closing entry #${waiting.id} is waiting for approval.`);
  if (!b.proposal) badRequest("Nothing left to close in this book.");
  const { data, error } = await db.rpc("create_entries", {
    p_user: user.id,
    p_entries: [{ ...toDbEntry(b.proposal), form: { generated: "closing", period: `${year}-12` } }],
    p_submit: true,
  });
  dbError(error);
  return c.json({ entryIds: data });
});
